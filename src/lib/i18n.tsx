export const getTranslation = (key: string, lang: Language = 'fr', fallback?: string): string => {
  const langDict = translations[lang] || translations.fr;
  if (langDict && langDict[key]) return langDict[key];
  if (translations.fr && translations.fr[key]) return translations.fr[key];
  if (fallback !== undefined) return fallback;
  return key;
};

export const applyLanguageDOM = (lang: Language): void => {
  if (typeof document === 'undefined') return;
  const isRTL = lang === 'ar';
  document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
};

interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string, fallback?: string) => string;
  isRTL: boolean;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'fr',
  setLanguage: () => {},
  t: (key: string, fallback?: string) => getTranslation(key, 'fr', fallback),
  isRTL: false,
});

export const LanguageProvider: React.FC<{
  language: Language;
  onLanguageChange?: (lang: Language) => void;
  children: React.ReactNode;
}> = ({ language, onLanguageChange, children }) => {
  useEffect(() => {
    applyLanguageDOM(language);
  }, [language]);

  const t = (key: string, fallback?: string) => getTranslation(key, language, fallback);
  const isRTL = language === 'ar';

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage: (lang) => onLanguageChange?.(lang),
        t,
        isRTL,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
